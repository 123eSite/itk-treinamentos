                                <p>Um vício psicológico é um tipo de dependência onde o elemento central é a necessidade
                                    psíquica, ao invés de uma dependência física.</p>
                                <p>Neste contexto, o indivíduo busca no vício uma forma de escapismo da realidade,
                                    ansiando pelos efeitos psicológicos como sensações de bem-estar, esquecimento dos
                                    problemas, e outros benefícios emocionais temporários.</p>
                                <p>Este tipo de vício se caracteriza pela relação intensa e muitas vezes compulsiva que
                                    a pessoa desenvolve com o objeto do seu vício.</p>
                                <p>Na ausência deste, o indivíduo experimenta um mal-estar significativo, que o
                                    impulsiona a buscar novamente a fonte do vício para alívio ou fuga.</p>
                                <p>Os efeitos psicológicos proporcionados pelo vício podem incluir:</p>
                                <ul>
                                    <li>Sensação de prazer: um sentimento intenso de satisfação ou alegria.</li>
                                    <li>Relaxamento intenso: uma redução acentuada de tensão ou ansiedade.</li>
