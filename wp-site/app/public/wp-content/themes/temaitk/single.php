                                <h2>Sinais e sintomas de um vício psicológico</h2>
                                <p>Para abordar eficazmente um vício psicológico, é fundamental entender seus sinais e
                                    sintomas.</p>
                                <p>Esta compreensão permite uma identificação mais precisa das crises e do aumento
                                    progressivo da dependência.</p>
                                <p>Os sintomas de um vício psicológico podem variar de acordo com o indivíduo e o objeto
                                    do vício, mas geralmente incluem:</p>
