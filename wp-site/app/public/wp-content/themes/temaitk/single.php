                                    <li>Alegria: sentimento de contentamento e felicidade.</li>
                                    <li>Sensação de poder: um sentimento de controle ou domínio aumentado.</li>
                                    <li>Felicidade plena: uma experiência de completa satisfação e contentamento.</li>
                                </ul>
